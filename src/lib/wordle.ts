const ANSWER_SET = new Set(WORDLE_ANSWERS);

export type LetterState = 'correct' | 'present' | 'absent' | 'empty';

export function isValidGuess(word: string): boolean {
  const w = word.trim().toLowerCase();
  return w.length === WORDLE_LEN && ANSWER_SET.has(w);
}

export function pickAnswer(seed?: string): string {
  if (!seed) {
    return WORDLE_ANSWERS[Math.floor(Math.random() * WORDLE_ANSWERS.length)]!;
  }
  // Stable daily-ish pick from a string seed (e.g. YYYY-MM-DD)
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return WORDLE_ANSWERS[h % WORDLE_ANSWERS.length]!;
}

export function todaySeed(): string {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

/**
 * Score a guess against the answer (Wordle rules: greens first, then yellows
 * with correct multiplicity — no double-counting a letter).
 */
export function scoreGuess(guess: string, answer: string): LetterState[] {
  const g = guess.toLowerCase();
  const a = answer.toLowerCase();
  const out: LetterState[] = Array.from({ length: WORDLE_LEN }, () => 'absent');
  const remaining: Record<string, number> = {};
  for (let i = 0; i < WORDLE_LEN; i++) {
    if (g[i] === a[i]) {
      out[i] = 'correct';
    } else {
      const ch = a[i]!;
      remaining[ch] = (remaining[ch] || 0) + 1;
    }
  }
  for (let i = 0; i < WORDLE_LEN; i++) {
    if (out[i] === 'correct') continue;
    const ch = g[i]!;
    if (remaining[ch]) {
      out[i] = 'present';
      remaining[ch]!--;
    }
  }
  return out;
}

export type WordleStatus = 'playing' | 'won' | 'lost';

export type WordleState = {
  answer: string;
  guesses: string[];
  status: WordleStatus;
  mode: 'daily' | 'random';
  seed?: string;
};

export function evaluateStatus(guesses: string[], answer: string): WordleStatus {
  if (guesses.some((g) => g === answer)) return 'won';
  if (guesses.length >= WORDLE_ROWS) return 'lost';
  return 'playing';
}

export function newWordleGame(mode: 'daily' | 'random'): WordleState {
  if (mode === 'daily') {
    const seed = todaySeed();
    const answer = pickAnswer(seed);
    return { answer, guesses: [], status: 'playing', mode, seed };
  }
  return {
    answer: pickAnswer(),
    guesses: [],
    status: 'playing',
    mode: 'random',
  };
}
